#!/usr/bin/env python3
"""Write the oracle's golden permutation vectors (ai/TESTING.md §2, M01 S5).

    python scripts/make_golden.py            write tests/golden/oracle_perm_n{64,1024,65536}.json
    python scripts/make_golden.py --check    regenerate in memory and compare with the files on disk
    python scripts/make_golden.py --quick    skip n = 65536

The output is a pure function of the fixed test key, so two runs are byte-identical. `--seed` is
accepted for CLI uniformity (CONVENTIONS §1) and has no effect.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tests"))

from testkeys import TEST_K_MASTER  # noqa: E402
from vcloak.oracle import crypto_hooks  # noqa: E402
from vcloak.oracle.reference import epoch_permutation_ref, reshuffle_permutation_ref  # noqa: E402

SIZES = (64, 1024, 65536)
NUMBERS = (0, 1, 7)  # epochs for the write path, windows for the re-shuffle
SOURCE = ("V-cloak reference oracle (vcloak.oracle.reference.epoch_permutation_ref / reshuffle_permutation_ref), "
          "generated by scripts/make_golden.py; tags per ai/ARCHITECTURE.md §5 with ChaCha20 as in RFC 8439 §2.3-2.4")


def file_name(n: int) -> str:
    return f"oracle_perm_n{n}.json"


def _vector(hi: np.ndarray, lo: np.ndarray, perm: np.ndarray) -> dict[str, str]:
    tags = np.column_stack([hi, lo]).astype("<u8").tobytes()
    raw = perm.astype("<u4").tobytes()
    return {"tags_sha256": hashlib.sha256(tags).hexdigest(), "perm_sha256": hashlib.sha256(raw).hexdigest(),
            "perm_b64": base64.b64encode(raw).decode("ascii")}


def build(n: int) -> bytes:
    """The golden file for size n, as the exact bytes written to disk."""
    k_tag, _, _ = crypto_hooks.derive_subkeys(TEST_K_MASTER)
    vectors = []
    for number in NUMBERS:
        vectors.append({
            "number": number,
            "epoch": _vector(*crypto_hooks.tags_for_epoch(k_tag, number, n), epoch_permutation_ref(k_tag, number, n)),
            "reshuffle": _vector(*crypto_hooks.reshuffle_tags(k_tag, number, n),
                                 reshuffle_permutation_ref(k_tag, number, n)),
        })
    doc = {
        "source": SOURCE,
        "key": "K_tag = derive_subkeys(TEST_K_MASTER)[0], TEST_K_MASTER from tests/testkeys.py (test key only)",
        "n": n,
        "perm_format": "base64 of n little-endian uint32; perm[p] = input slot stored at output position p",
        "tags_format": "sha256 over the 16n tag bytes, slot by slot: LE64(hi) || LE64(lo)",
        "sort_key": "(hi, lo, slot) ascending",
        "vectors": vectors,
    }
    return (json.dumps(doc, indent=1, sort_keys=True) + "\n").encode("ascii")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(ROOT / "tests" / "golden"), help="directory of the golden files")
    ap.add_argument("--check", action="store_true", help="compare with the existing files instead of writing")
    ap.add_argument("--quick", action="store_true", help="skip n = 65536")
    ap.add_argument("--seed", type=int, default=0, help="unused: the vectors are deterministic")
    a = ap.parse_args(argv)

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    bad = 0
    for n in SIZES[:-1] if a.quick else SIZES:
        data = build(n)
        path = out / file_name(n)
        digest = hashlib.sha256(data).hexdigest()
        if a.check:
            same = path.is_file() and path.read_bytes() == data
            bad += not same
            print(f"{digest}  {path.name}  {'identical' if same else 'DIFFERS'}")
        else:
            path.write_bytes(data)
            print(f"{digest}  {path.name}  written")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
