            if suffix:
                out += [(f"resTurn{suffix}", m(f"S-TURNACC-{layout}", "attack", _f(1, 100))),
                        (f"resSame{suffix}", m(f"S-F-{layout}", "attack", _f(1, 100))),
                        (f"resTauG{suffix}", m(f"S-TAU-GLOBAL-{layout}", "attack", _f(3)))]
