class ExportError(Exception):
    """An input is missing or is not what the exporter may read."""


@dataclass
class V:
    """One exported value and where it came from."""
    text: str
    raw: Any = None
    ok: bool = True
    src: dict[str, Any] = field(default_factory=dict)


def _int(x: Any) -> str:
    return str(int(round(float(x))))


def _f(digits: int, scale: float = 1.0) -> Callable[[Any], str]:
    def fmt(x: Any) -> str:
        text = f"{float(x) * scale:.{digits}f}"
        return text.lstrip("-") if not text.strip("-0.") else text  # never print a negative zero
    return fmt


def _ms(x: Any) -> str:
    x = float(x)
    return f"{x:.3f}" if x < 10 else f"{x:.2f}" if x < 100 else f"{x:.1f}" if x < 1000 else f"{x:.0f}"


def tex_escape(s: Any) -> str:
    out = str(s).replace(BS, BS + "textbackslash ")
    for ch in "&%$#_{}":
        out = out.replace(ch, BS + ch)
    return out.replace("~", BS + "textasciitilde ").replace("^", BS + "textasciicircum ")


class Exporter:
    def __init__(self, root: Path = ROOT) -> None:
        self.root = root
        rows, errs = check_metrics.parse_index(root / "state" / "METRICS_INDEX.md")
        if errs:
            raise ExportError("state/METRICS_INDEX.md does not parse: " + "; ".join(errs[:3]))
        self.index = {(r["id"], r["run_dir"]): r for r in rows}
        self.runs: dict[str, str] = {}
        for area, name in (("perf", "perf_summary.json"), ("security", "security_summary.json"),
                           ("oblivious", "oblivious_summary.json")):
            summary = self._load(Path("results") / area / name)
            if summary.get("backend") != "cupy":
                raise ExportError(f"results/{area}/{name}: backend {summary.get('backend')}, "
                                  "not an ingested cupy session")
            self.runs.update(summary["run_dirs"])
            if area == "oblivious":
                self.kernel_window = summary.get("kernel_window", {})
        self.runs["session"] = "runs/" + self._load(Path("results") / "session" / "e5_matrix.json")["run_id"]
        self.quick = {k: bool(self._load(Path(d) / "manifest.json")["quick"]) for k, d in self.runs.items()}
        self.entries: list[dict[str, Any]] = []
        self.files: dict[str, str] = {}

    # ------------------------------------------------------------------ sources
    def _load(self, rel: Path) -> Any:
        p = self.root / rel
        if not p.is_file():
            raise ExportError(f"{rel.as_posix()} is missing")
        return json.loads(p.read_text(encoding="utf-8"))

    def metric(self, mid: str, run: str, fmt: Callable[[Any], str], run_dir: str | None = None) -> V:
        run_dir = run_dir or self.runs[run]
        src = {"kind": "metric", "metric_ids": [mid], "run_dir": run_dir}
        row = self.index.get((mid, run_dir))
        if row is None:
            return V(PENDING, ok=False, src={**src, "kind": "pending", "reason": "no index row for this run"})
        if row["quick"].lower() in ("yes", "true", "quick"):
            return V(PENDING, ok=False, src={**src, "kind": "pending", "reason": "quick run (audit A2)"})
        if row["value"] in NO_VALUE:
            return V(NO_VALUE[row["value"]], ok=False, src={**src, "kind": "pending", "reason": row["value"]})
        return V(fmt(row["value"]), raw=float(row["value"]), src={**src, "unit": row["unit"], "backend": row["backend"],
                                                                 "runner": row["runner"]})

    def field(self, run: str, file: str, path: str, fmt: Callable[[Any], str], kind: str = "field") -> V:
        src = {"kind": kind, "metric_ids": [], "run_dir": self.runs[run], "file": file, "path": path}
        if self.quick[run]:
            return V(PENDING, ok=False, src={**src, "kind": "pending", "reason": "quick run (audit A2)"})
        cur = self._load(Path(self.runs[run]) / file)
        for part in path.split("."):
            cur = cur[int(part)] if isinstance(cur, list) else cur[part]
        return V(fmt(cur), raw=cur, src=src)

    def derived(self, how: str, fmt: Callable[[Any], str], fn: Callable[..., float], *parts: V) -> V:
        src = {"kind": "derived", "how": how, "metric_ids": [m for p in parts for m in p.src.get("metric_ids", [])],
               "from": [p.src for p in parts]}
        bad = [p for p in parts if not p.ok]
        if bad:
            return V(bad[0].text, ok=False, src={**src, "kind": "pending", "reason": bad[0].src.get("reason")})
        raw = fn(*(p.raw for p in parts))
        return V(fmt(raw), raw=raw, src=src)

    def pending(self, reason: str) -> V:
        return V(PENDING, ok=False, src={"kind": "pending", "metric_ids": [], "reason": reason})

    def note(self, target: str, name: str, v: V) -> str:
        self.entries.append({"target": target, "name": name, "value": v.text, **v.src})
        return v.text

    # ------------------------------------------------------------------ macros.tex
