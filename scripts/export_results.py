#!/usr/bin/env python3
"""M16: turn the indexed metrics into the files the paper and the deck read. No number is typed here.

    python scripts/export_results.py                      # write results/paper, results/figures, the two .md files
    python scripts/export_results.py --check              # write nothing; exit 1 if the files on disk would change

Every exported value has one of these sources, and `results/paper/macro_map.json` names it for every macro and cell:
  metric   a row of state/METRICS_INDEX.md, chosen by (metric id, run dir);
  field    a value of an output file of a run dir that has no index row of its own (the map gives file and path);
  param    a public parameter of a run (n, epochs, buckets), read from the same files;
  derived  computed here from values of the kinds above (the map lists them);
  pending  no value: a quick run, an UNSTABLE or NOT_MEASURED row, or a measurement that does not exist yet.
The run dirs are the ones the generated summaries of results/perf, results/security and results/oblivious name.
A value that is UNSTABLE prints `\\unstable`, a NOT_MEASURED one `\\notmeasured`, a missing one `\\pending`.
Macro and file names are those of seed/PAPER_RESULTS_CONTRACT.md; its interim values are read only to list what
changed (results/PAPER_UPDATES.md, results/deck_numbers.md) and are never written as results.
"""
